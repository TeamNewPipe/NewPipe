package org.schabi.newpipe.transcript

import android.content.Context
import io.reactivex.rxjava3.core.Single
import io.reactivex.rxjava3.schedulers.Schedulers
import org.schabi.newpipe.download.DownloadedCopyRepository
import org.schabi.newpipe.download.OfflinePlaybackMetadata
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import org.schabi.newpipe.profiles.ProfileManager
import org.schabi.newpipe.util.ExtractorHelper

internal data class TranscriptRequest(
    val service: Int,
    val url: String,
    val profile: String,
    val localUri: String? = null,
    val localIdentity: String? = null
)

internal data class TranscriptSource(
    val info: StreamInfo?,
    val tracks: List<SubtitlesStream>,
    val captionIdentities: Map<String, String> = emptyMap()
)

/** Local requests never fall back to extraction, including after a file is replaced or deleted. */
internal object TranscriptSourceRepository {
    fun load(
        context: Context,
        request: TranscriptRequest,
        network: () -> Single<StreamInfo> = { ExtractorHelper.getStreamInfo(request.service, request.url, false) }
    ): Single<TranscriptSource> = Single.defer {
        checkProfile(context, request)
        val localUri = request.localUri
        if (localUri != null) {
            val local = OfflinePlaybackMetadata.resolve(context, localUri)
            check(!request.localIdentity.isNullOrEmpty() && local.identity == request.localIdentity) { "Media file changed" }
            val source = checkNotNull(local.sourceInfo) { "Download metadata unavailable" }
            check(source.serviceId == request.service && DownloadedCopyRepository.sameSource(request.service, source.url, request.url)) { "Download source changed" }
            Single.just(TranscriptSource(source, local.subtitles, local.captionIdentities))
        } else {
            network().map { TranscriptSource(it, it.subtitles) }
        }
    }.map { source ->
        checkProfile(context, request)
        source.copy(tracks = source.tracks.filter(TranscriptRepository::supports).distinctBy { it.languageTag to it.isAutoGenerated })
    }.subscribeOn(Schedulers.io())

    private fun checkProfile(context: Context, request: TranscriptRequest) {
        check(request.profile == ProfileManager.getActiveProfileId(context)) { "Profile changed" }
    }
}
