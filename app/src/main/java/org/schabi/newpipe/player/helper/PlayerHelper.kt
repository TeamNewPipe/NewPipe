object PlayerHelper {
    private val FORMATTERS_PROVIDER = FormattersProvider()

    @Retention(AnnotationRetention.SOURCE)
    @IntDef(AUTOPLAY_TYPE_ALWAYS, AUTOPLAY_TYPE_WIFI, AUTOPLAY_TYPE_NEVER)
    annotation class AutoplayType

    const val AUTOPLAY_TYPE_ALWAYS = 0
    const val AUTOPLAY_TYPE_WIFI = 1
    const val AUTOPLAY_TYPE_NEVER = 2

    @Retention(AnnotationRetention.SOURCE)
    @IntDef(MINIMIZE_ON_EXIT_MODE_NONE, MINIMIZE_ON_EXIT_MODE_BACKGROUND, MINIMIZE_ON_EXIT_MODE_POPUP)
    annotation class MinimizeMode

    const val MINIMIZE_ON_EXIT_MODE_NONE = 0
    const val MINIMIZE_ON_EXIT_MODE_BACKGROUND = 1
    const val MINIMIZE_ON_EXIT_MODE_POPUP = 2

    @JvmStatic
    fun resetFormat() {
        FORMATTERS_PROVIDER.reset()
    }

    @JvmStatic
    fun getTimeString(milliSeconds: Long): String {
        val seconds = (milliSeconds % 60000) / 1000
        val minutes = (milliSeconds % 3600000) / 60000
        val hours = (milliSeconds % 86400000) / 3600000
        val days = (milliSeconds % (86400000 * 7)) / 86400000

        val formatters = FORMATTERS_PROVIDER.formatters()
        return if (days > 0) {
            formatters.stringFormat("%d:%02d:%02d:%02d", days, hours, minutes, seconds)
        } else if (hours > 0) {
            formatters.stringFormat("%d:%02d:%02d", hours, minutes, seconds)
        } else {
            formatters.stringFormat("%02d:%02d", minutes, seconds)
        }
    }

    @JvmStatic
    fun formatSpeed(speed: Double): String {
        return FORMATTERS_PROVIDER.formatters().speed.format(speed)
    }

    @JvmStatic
    fun formatPitch(pitch: Double): String {
        return FORMATTERS_PROVIDER.formatters().pitch.format(pitch)
    }

    @JvmStatic
    fun captionLanguageOf(context: Context, subtitles: SubtitlesStream): String {
        val displayName = subtitles.displayLanguageName
        return displayName + (if (subtitles.isAutoGenerated) " (" + context.getString(R.string.caption_auto_generated) + ")" else "")
    }

    @JvmStatic
    fun captionLanguageStemOf(language: String): String {
        if (!language.contains("(") || !language.contains(")")) {
            return language
        }

        if (language.startsWith("(")) {
            // language text is right-to-left
            val parts = language.split("\\)".toRegex()).dropLastWhile { it.isEmpty() }.toTypedArray()
            return parts[parts.size - 1].trim { it <= ' ' }
        }

        return language.split("\\(".toRegex()).dropLastWhile { it.isEmpty() }.toTypedArray()[0].trim { it <= ' ' }
    }

    @JvmStatic
    fun resizeTypeOf(context: Context, resizeMode: Int): String {
        return when (resizeMode) {
            AspectRatioFrameLayout.RESIZE_MODE_FIT -> context.getString(R.string.resize_fit)
            AspectRatioFrameLayout.RESIZE_MODE_FILL -> context.getString(R.string.resize_fill)
            AspectRatioFrameLayout.RESIZE_MODE_ZOOM -> context.getString(R.string.resize_zoom)
            else -> throw IllegalArgumentException("Unrecognized resize mode: $resizeMode")
        }
    }

    @JvmStatic
    fun autoQueueOf(info: StreamInfo, existingItems: List<PlayQueueItem>): PlayQueue? {
        val urls = existingItems.map { it.url }.toSet()

        val relatedItems = info.relatedItems
        if (Utils.isNullOrEmpty(relatedItems)) {
            return null
        }

        if (relatedItems[0] is StreamInfoItem && !urls.contains(relatedItems[0].url)) {
            return getAutoQueuedSinglePlayQueue(relatedItems[0] as StreamInfoItem)
        }

        val autoQueueItems = relatedItems
            .filterIsInstance<StreamInfoItem>()
            .filter { !urls.contains(it.url) }
            .shuffled()

        return if (autoQueueItems.isEmpty()) null else getAutoQueuedSinglePlayQueue(autoQueueItems[0])
    }

