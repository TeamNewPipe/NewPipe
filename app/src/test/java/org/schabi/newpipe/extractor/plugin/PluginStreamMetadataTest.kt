class PluginStreamMetadataTest {
    @Test
    fun savedStreamInfoFromBeforePluginsKeepsNestedStreamsAndGetsCompatibleMetadataDefaults() {
        val input = requireNotNull(javaClass.getResourceAsStream("/plugin-fixtures/legacy-stream-info-v1.51.ser"))
        val info = ObjectInputStream(input).use { it.readObject() as StreamInfo }
        assertEquals("Legacy stream", info.name)
        assertEquals("https://fixture.example/watch", info.url)
        assertEquals(90L, info.duration)
        assertTrue(info.isSpherical)
        assertTrue(info.isUpcoming)
        assertTrue(info.isSupportBulletComments)
        assertNull(info.manifestRequestHeaders)
        val audio = info.audioStreams.single()
        val video = info.videoStreams.single()
        val subtitles = info.subtitles.single()
        assertEquals(AudioTrackType.DESCRIPTIVE, audio.audioTrackType)
        assertEquals("Description track", audio.audioTrackName)
        assertEquals(128, audio.averageBitrate)
        assertEquals("720p", video.resolution)
        assertEquals("en-US", subtitles.languageTag)
        for (stream in listOf(audio, video, subtitles)) {
            assertTrue(stream.isUrl)
            assertEquals(Stream.AVAILABLE_AT_UNKNOWN, stream.availableAt)
            assertNull(stream.deliveryMethodInfo)
            assertNull(stream.requestHeaders)
            assertNull(stream.cacheable)
        }
        // A real provider opt-out must remain false after saving, including restored objects.
        info.setSupportBulletComments(false)
        val bytes = ByteArrayOutputStream().also { output -> ObjectOutputStream(output).use { it.writeObject(info) } }.toByteArray()
        val restored = ObjectInputStream(ByteArrayInputStream(bytes)).use { it.readObject() as StreamInfo }
        assertFalse(restored.isSupportBulletComments)
        assertEquals(Stream.AVAILABLE_AT_UNKNOWN, restored.videoStreams.single().availableAt)
    }

    @Test
    fun streamBuildersCarryPluginRequestMetadataWithoutLosingExistingAudioTrackTypes() {
        val headers = mutableMapOf("Referer" to "https://fixture.example/")
        val video = VideoStream.Builder()
            .setId("video")
            .setContent("https://media.example/video", true)
            .setIsVideoOnly(false)
            .setResolution("720p")
            .setRequestHeaders(headers)
            .setCacheable(false)
            .setAvailableAt(12345)
            .setDeliveryMethodInfo("fixture metadata")
            .build()
        val audio = AudioStream.Builder()
            .setId("audio")
            .setContent("https://media.example/audio", true)
            .setAudioTrackType(AudioTrackType.DESCRIPTIVE)
            .setRequestHeaders(headers)
            .setCacheable(false)
            .setAvailableAt(12345)
            .setDeliveryMethodInfo("fixture metadata")
            .build()
        val subtitle = SubtitlesStream.Builder()
            .setContent("https://media.example/subtitles", true)
            .setLanguageCode("en")
            .setAutoGenerated(false)
            .setMediaFormat(MediaFormat.VTT)
            .setRequestHeaders(headers)
            .setCacheable(false)
            .build()
        headers["Referer"] = "https://changed.example/"
        for (stream in listOf(video, audio, subtitle)) {
            assertEquals("https://fixture.example/", stream.requestHeaders!!["Referer"])
            assertFalse(stream.cacheable!!)
            assertThrows(UnsupportedOperationException::class.java) { stream.requestHeaders!!["Other"] = "value" }
        }
        assertEquals(AudioTrackType.DESCRIPTIVE, audio.audioTrackType)
        assertEquals(12345L, audio.availableAt)
        assertEquals("fixture metadata", audio.deliveryMethodInfo)
        val bytes = ByteArrayOutputStream().also { output -> ObjectOutputStream(output).use { it.writeObject(video) } }.toByteArray()
        val restored = ObjectInputStream(ByteArrayInputStream(bytes)).use { it.readObject() as VideoStream }
        assertEquals(video.requestHeaders, restored.requestHeaders)
        assertEquals(video.availableAt, restored.availableAt)
        assertEquals(video.deliveryMethodInfo, restored.deliveryMethodInfo)
        assertEquals(video.cacheable, restored.cacheable)
    }

    @Test
    fun manifestHeadersAreSnapshotsAndDoNotChangeExistingStreamFlags() {
        val info = StreamInfo(12345, "https://fixture.example/video", "https://fixture.example/video", StreamType.VIDEO_STREAM, "video", "Fixture", 0)
        val headers = mutableMapOf("Referer" to "https://fixture.example/")
        info.manifestRequestHeaders = headers
        info.isUpcoming = true
        info.isSpherical = true
        headers.clear()
        assertEquals("https://fixture.example/", info.manifestRequestHeaders!!["Referer"])
        assertThrows(UnsupportedOperationException::class.java) { info.manifestRequestHeaders!!.clear() }
        assertEquals(true, info.isUpcoming)
        assertEquals(true, info.isSpherical)
        info.manifestRequestHeaders = emptyMap()
        assertEquals(null, info.manifestRequestHeaders)
    }
}
