import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.SubtitlesStream

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [35], application = Application::class)
class SecondaryCaptionLoaderTest {
    @Test fun byteLimitAppliesWithoutAContentLengthAndCancellationStopsReading() {
        assertThrows(IllegalArgumentException::class.java) {
            SecondaryCaptionLoader.readBounded(ByteArrayInputStream(ByteArray(SecondaryCaptionLoader.MAX_BYTES + 1))) { false }
        }
        var reads = 0
        val input = object : InputStream() {
            override fun read(): Int {
                reads++
                return 'a'.code
            }
            override fun read(bytes: ByteArray, offset: Int, length: Int): Int = 0
        }
        assertThrows(CancellationException::class.java) {
            SecondaryCaptionLoader.readBounded(input) { reads > 0 }
        }
        assertEquals(1, reads)
    }

    @Test fun cancellingTheAwaitingUiCancelsItsHttpCall() = runBlocking {
        val call = mock(Call::class.java)
        val started = CountDownLatch(1)
        val cancelled = CountDownLatch(1)
        doAnswer {
            cancelled.countDown()
            null
        }.`when`(call).cancel()
        `when`(call.execute()).thenAnswer {
            started.countDown()
            cancelled.await(5, TimeUnit.SECONDS)
            throw IOException("Cancelled request")
        }
        val track = track("https://example.invalid/captions.vtt", true)
        val request = launch(Dispatchers.Default) {
            SecondaryCaptionLoader.load(RuntimeEnvironment.getApplication(), track, remoteCall = { call }).await()
        }
        assertTrue("Caption request did not start", started.await(5, TimeUnit.SECONDS))
        request.cancelAndJoin()
        assertTrue("Closing the UI did not cancel HTTP", cancelled.await(5, TimeUnit.SECONDS))
    }

    @Test fun inlineCaptionsKeepTheirTimingAndUnknownUriSchemesNeverReachHttp() {
        val context: Application = RuntimeEnvironment.getApplication()
        val inline = track("WEBVTT\n\n00:01.250 --> 00:02.000\nInline caption\n", false)
        val subtitle = SecondaryCaptionLoader.load(context, inline) { error("Inline caption requested HTTP") }.blockingGet()
        assertEquals("Inline caption", subtitle.getCues(1_250_000).single().text.toString())
        SecondaryCaptionLoader.load(context, track("ftp://example.invalid/captions.vtt", true)) { error("Unsupported URI requested HTTP") }
            .test().awaitDone(5, TimeUnit.SECONDS).assertNoValues().assertError(IllegalArgumentException::class.java)
    }

    private fun track(content: String, url: Boolean) = SubtitlesStream.Builder().setId("test")
        .setContent(content, url).setLanguageCode("en").setAutoGenerated(false).setMediaFormat(MediaFormat.VTT).build()
}
