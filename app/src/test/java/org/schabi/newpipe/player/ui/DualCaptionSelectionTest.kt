package org.schabi.newpipe.player.ui

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.SubtitlesStream

class DualCaptionSelectionTest {
    private fun sub(code: String, auto: Boolean) = SubtitlesStream.Builder()
        .setContent("WEBVTT", false)
        .setLanguageCode(code)
        .setMediaFormat(MediaFormat.VTT)
        .setAutoGenerated(auto)
        .build()

    @Test fun prefersHumanSubtitleWithinTheSelectedLanguage() {
        val auto = sub("fr", true)
        val manual = sub("fr", false)
        assertEquals(manual, DualCaptionSelection.select(listOf(auto, manual), "fr"))
    }

    @Test fun leavesUnavailableLanguagesOff() {
        assertNull(DualCaptionSelection.select(listOf(sub("fr", false)), "en"))
    }
}
