package org.schabi.newpipe.player.ui

import android.content.Context
import androidx.core.content.FileProvider
import androidx.preference.PreferenceManager
import androidx.test.core.app.ApplicationProvider
import java.util.concurrent.TimeUnit
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Test
import org.schabi.newpipe.download.DownloadedCopyRepository
import org.schabi.newpipe.download.OfflineDownloadFixture
import org.schabi.newpipe.extractor.stream.SubtitlesStream

class OfflineSecondaryCaptionsTest {
    private val context = ApplicationProvider.getApplicationContext<Context>()

    @Test fun downloadedTracksUseTheProductionSecondaryLoaderForFilesAndContentAliases() {
        val preferences = PreferenceManager.getDefaultSharedPreferences(context)
        val original = preferences.all[DownloadedCopyRepository.PREFERENCE] as? Boolean
        preferences.edit().putBoolean(DownloadedCopyRepository.PREFERENCE, true).commit()
        try {
            OfflineDownloadFixture(context).use { fixture ->
                fixture.register()
                val copy = checkNotNull(DownloadedCopyRepository.find(context, 0, fixture.source, null, false))
                val track = copy.subtitles.single()
                val identity = copy.captionIdentities[track.content]
                assertNotNull("Downloaded playback must retain the caption identity", identity)
                val alias = FileProvider.getUriForFile(context, "${context.packageName}.provider", fixture.caption).toString()
                val aliased = SubtitlesStream.Builder().setId("alias").setContent(alias, true)
                    .setLanguageCode("en").setAutoGenerated(false).setMediaFormat(track.format).build()
                for (localTrack in listOf(track, aliased)) {
                    val subtitle = SecondaryCaptionLoader.load(context, localTrack, identity) {
                        error("A local secondary caption tried to open an HTTP request")
                    }.blockingGet()
                    assertEquals("First offline line", subtitle.getCues(1_250_000).single().text.toString())
                    assertEquals("Second offline line", subtitle.getCues(5_000_000).single().text.toString())
                    assertEquals(emptyList<Any>(), subtitle.getCues(4_000_000))
                }

                SecondaryCaptionLoader.load(context, track, null) { error("Unverified caption tried HTTP") }
                    .test().awaitDone(5, TimeUnit.SECONDS).assertNoValues().assertError(IllegalArgumentException::class.java)

                val originalModified = fixture.caption.lastModified()
                val changed = fixture.caption.readBytes().apply { this[lastIndex - 1] = 'x'.code.toByte() }
                fixture.caption.writeBytes(changed)
                fixture.caption.setLastModified(originalModified)
                SecondaryCaptionLoader.load(context, track, identity) { error("Changed caption tried HTTP") }
                    .test().awaitDone(5, TimeUnit.SECONDS).assertNoValues().assertError(IllegalArgumentException::class.java)

                fixture.caption.delete()
                SecondaryCaptionLoader.load(context, aliased, identity) { error("Missing caption tried HTTP") }
                    .test().awaitDone(5, TimeUnit.SECONDS).assertNoValues().assertError(IllegalArgumentException::class.java)
            }
        } finally {
            preferences.edit().apply {
                if (original == null) {
                    remove(DownloadedCopyRepository.PREFERENCE)
                } else {
                    putBoolean(DownloadedCopyRepository.PREFERENCE, original)
                }
            }.commit()
        }
    }
}
