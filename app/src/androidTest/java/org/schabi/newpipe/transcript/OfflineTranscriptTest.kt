import io.reactivex.rxjava3.subjects.SingleSubject
import java.util.concurrent.CountDownLatch
import java.util.concurrent.TimeUnit
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test
import org.schabi.newpipe.download.OfflineDownloadFixture
import org.schabi.newpipe.download.OfflinePlaybackMetadata
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.player.OfflineTimestampTargetResolver
import org.schabi.newpipe.player.TimestampChangeData
import org.schabi.newpipe.player.playqueue.PlayQueueItem
import org.schabi.newpipe.profiles.ProfileManager

class OfflineTranscriptTest {
    private val context = ApplicationProvider.getApplicationContext<Context>()

    @Test fun coldLocalRequestsReadFileAndContentCaptionsWithoutInvokingExtraction() {
        OfflineDownloadFixture(context).use { fixture ->
            fixture.register()
            val resolved = OfflinePlaybackMetadata.resolve(context, fixture.uri())
            val request = TranscriptRequest(0, fixture.source, ProfileManager.getActiveProfileId(context), fixture.uri(), resolved.identity)
            val source = TranscriptSourceRepository.load(context, request) { error("Local transcript tried to extract online metadata") }.blockingGet()
            val track = source.tracks.single()
            val expected = listOf(TranscriptLine(1250, "First offline line"), TranscriptLine(5000, "Second offline line"))
            assertEquals(expected, TranscriptRepository.load(context, track, source.captionIdentities[track.content]).blockingGet())
            val alias = FileProvider.getUriForFile(context, "${context.packageName}.provider", fixture.caption).toString()
            val aliased = org.schabi.newpipe.extractor.stream.SubtitlesStream.Builder().setId("alias")
                .setContent(alias, true).setLanguageCode("en").setAutoGenerated(false).setMediaFormat(track.format).build()
            assertEquals(expected, TranscriptRepository.load(context, aliased, source.captionIdentities[track.content]).blockingGet())
            assertEquals(listOf(expected[1]), TranscriptRepository.filter(expected, "SECOND"))
            fixture.caption.delete()
            TranscriptRepository.load(context, track, source.captionIdentities[track.content]).test()
                .awaitDone(5, TimeUnit.SECONDS).assertNoValues().assertError(IllegalArgumentException::class.java)
            assertTrue(TranscriptSourceRepository.load(context, request) { error("Missing local captions triggered a network fallback") }.blockingGet().tracks.isEmpty())
        }
    }

    @Test fun changedMediaAndWrongSourceCannotReuseAnOpenTranscriptOrTimestamp() {
        OfflineDownloadFixture(context).use { fixture ->
            fixture.register()
            val resolved = OfflinePlaybackMetadata.resolve(context, fixture.uri())
            val profile = ProfileManager.getActiveProfileId(context)
            val request = TranscriptRequest(0, "https://www.youtube.com/watch?v=aaaaaaaaaaa", profile, fixture.uri(), resolved.identity)
            TranscriptSourceRepository.load(context, request) { error("Wrong-source local request tried extraction") }.test()
                .awaitDone(5, TimeUnit.SECONDS).assertNoValues().assertError(IllegalStateException::class.java)
            val data = TimestampChangeData(0, fixture.source, 1, fixture.uri(), resolved.identity, profile, 1250)
            val alias = FileProvider.getUriForFile(context, "${context.packageName}.provider", fixture.video).toString()
            val current = PlayQueueItem.localMedia("Alias", alias, 8, null, null, null, "video/mp4", -1, true, null)
            val target = OfflineTimestampTargetResolver.resolve(context, data, current)
            assertTrue(target.item.isLocalMedia)
            assertTrue(target.matchesCurrent)
            assertEquals(fixture.uri(), target.item.url)
            fixture.video.appendBytes(byteArrayOf(1))
            assertThrows(IllegalStateException::class.java) { OfflineTimestampTargetResolver.resolve(context, data, current) }
            TranscriptSourceRepository.load(context, request.copy(url = fixture.source)) { error("Changed file triggered extraction") }.test()
                .awaitDone(5, TimeUnit.SECONDS).assertNoValues().assertError(IllegalStateException::class.java)
        }
    }

    @Test fun profileSwitchAndDisposedDialogsDiscardLateSourceResults() {
        val original = ProfileManager.getActiveProfileId(context)
        val other = checkNotNull(ProfileManager.createProfile(context, "Offline transcript ${System.nanoTime()}"))
        try {
            assertTrue(ProfileManager.setActiveProfile(context, original))
            val pending = SingleSubject.create<StreamInfo>()
            val subscribed = CountDownLatch(1)
            val request = TranscriptRequest(0, "https://www.youtube.com/watch?v=bbbbbbbbbbb", original)
            val result = TranscriptSourceRepository.load(context, request) {
                subscribed.countDown()
                pending
            }.test()
            assertTrue(subscribed.await(5, TimeUnit.SECONDS))
            assertTrue(ProfileManager.setActiveProfile(context, other.id))
            pending.onSuccess(StreamInfo(0, request.url, request.url, "Old profile"))
            result.awaitDone(5, TimeUnit.SECONDS).assertNoValues().assertError(IllegalStateException::class.java)
            assertTrue(ProfileManager.setActiveProfile(context, original))

            val cancelled = SingleSubject.create<StreamInfo>()
            val cancellationSubscribed = CountDownLatch(1)
            val disposed = TranscriptSourceRepository.load(context, request) {
                cancellationSubscribed.countDown()
                cancelled
            }.test()
            assertTrue(cancellationSubscribed.await(5, TimeUnit.SECONDS))
            disposed.dispose()
            assertFalse(cancelled.hasObservers())
            cancelled.onSuccess(StreamInfo(0, request.url, request.url, "Closed panel"))
            disposed.assertNoValues().assertNoErrors().assertNotComplete()
        } finally {
            ProfileManager.setActiveProfile(context, original)
            ProfileManager.deleteProfile(context, other.id)
        }
    }
}
